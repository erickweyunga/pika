//! Native code generation for Pika programs with Cranelift.
//!
//! [`compile`] translates every MIR body into Cranelift IR and compiles it into executable
//! memory (a JIT). The translation only uses Cranelift's generic `Module` interface, so
//! producing object files for standalone executables only needs a different module.
//!
//! The generated code follows the reference semantics of `pika_mir::value` exactly; the
//! differential tests run every program both compiled and interpreted.
//!
//! # Representation of values
//!
//! Scalars (integers, floats, `bool`, `char`, `Duration`) are machine values, and so is a
//! box: a pointer to its value on the heap. A `String` is a three-word structure in memory
//! (see `pika_runtime::string::PikaString`), a struct is its fields in memory, laid out as by
//! a C compiler, and an enum or option is a tag followed by the fields of its variant. Locals
//! holding scalars are SSA variables unless their address is taken; other locals live in
//! stack slots. Borrowed parameters are pointers. A function returning a value in memory
//! receives a pointer to the destination as a hidden first parameter.

